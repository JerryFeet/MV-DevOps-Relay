const translations: Record<Lang, Record<string, string>> = { en, ar };

/** Exposed for translation-guard tests only — do not use in production code. */
export const _testOnly = { en, ar };

export function t(lang: Lang, key: string): string {
  const value = translations[lang]?.[key];
  if (value !== undefined) return value;

  if (lang === "ar" && import.meta.env.DEV) {
    const fallback = translations.en[key] ?? key;
    console.warn(
      `[i18n] Missing Arabic translation for key: "${key}" — falling back to: "${fallback}"`
    );
  }

  return translations.en[key] ?? key;
}
